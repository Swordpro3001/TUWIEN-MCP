package dev.lecturetubemcp.api

import dev.lecturetubemcp.Config
import dev.lecturetubemcp.media.JobState
import dev.lecturetubemcp.media.MediaTools
import dev.lecturetubemcp.media.Transcriber

/** Result of building a transcript: [ok] = false means [text] explains why there is none. */
data class TranscriptResult(val ok: Boolean, val text: String, val title: String = "")

/**
 * Builds a timestamped transcript of a LectureTube lecture. Sources, in order:
 * 1. the lecture's WebVTT captions on LectureTube;
 * 2. a transcript generated earlier with Whisper (see `transcribe_recording`).
 * Shared by the LectureTube and TUWEL MCP servers.
 */
suspend fun LectureTubeService.transcript(
    lecture: String,
    lang: String? = null,
    format: String = "text",
    fromMinute: Int? = null,
    toMinute: Int? = null,
    paragraphSeconds: Int = 60,
    maxChars: Int = 100_000,
): TranscriptResult {
    val e = event(lecture)
    val link = "${Config.TOBIRA}/!v/${Ids.key(e.id)}"

    if (e.captions.isEmpty()) {
        Transcriber.cached(e.opencastId)?.let { (cues, meta) ->
            val header = "# ${e.title}\nLecture: $link | duration ${Vtt.fmt(e.durationMs)} | transcript generated by " +
                "${dev.lecturetubemcp.media.sourceLabel(meta)} from the recording's audio. Expect recognition errors in names and technical terms.\n\n"
            return TranscriptResult(true, MediaTools.transcriptText(header, cues, fromMinute, toMinute, format, paragraphSeconds, maxChars), e.title)
        }
        val running = Transcriber.job(e.opencastId)?.takeIf { it.state != JobState.FAILED && it.state != JobState.DONE }
        return TranscriptResult(
            false,
            buildString {
                append("\"${e.title}\" has no captions on LectureTube")
                if (!e.hasAuthorizedData) append(" (or you have no access to its media; try `login`)")
                append(".")
                val foreign = if (running == null) Transcriber.foreignStatus(e.opencastId) else null
                if (running != null) {
                    append(" A transcription is running: ${running.summary()}. Wait for it with transcription_status (returns as soon as it is ready).")
                } else if (foreign != null) {
                    append(" A transcription is running: $foreign. Wait for it with transcription_status (returns as soon as it is ready).")
                } else if (e.hasAuthorizedData) {
                    append(" Generate a transcript from the audio with `transcribe_recording` (lecture=\"${e.id}\"; takes about ")
                    append("${(e.durationMs / 60_000 / 8).coerceAtLeast(1)}–${(e.durationMs / 60_000 / 4).coerceAtLeast(2)} min on CPU; can be limited with fromMinute/toMinute).")
                }
                if (e.segments.isNotEmpty()) append(" It also has ${e.segments.size} detected slides (get_slides / analyze_keyframes).")
            },
            e.title,
        )
    }
    val wanted = lang?.lowercase() ?: when (e.language) {
        "deu", "ger", "de" -> "de"; "eng", "en" -> "en"; else -> null
    }
    val (usedLang, uri) = e.captions.firstOrNull { it.first?.lowercase() == wanted } ?: e.captions.first()
    val raw = client.getText(uri)
    if (format == "vtt") return TranscriptResult(true, raw.take(maxChars), e.title)
    val header = "# ${e.title}\nLecture: $link | duration ${Vtt.fmt(e.durationMs)} | transcript language: ${usedLang ?: "?"} " +
        "(available: ${e.captions.joinToString { it.first ?: "?" }})\nSource: LectureTube captions. May contain recognition errors.\n\n"
    return TranscriptResult(true, MediaTools.transcriptText(header, Vtt.parse(raw), fromMinute, toMinute, format, paragraphSeconds, maxChars), e.title)
}

/** Cues for a lecture from captions or a generated transcript, or null (used to annotate keyframes). */
suspend fun LectureTubeService.cuesFor(e: LectureTubeService.Event): List<Cue>? {
    if (e.captions.isNotEmpty()) {
        val wanted = when (e.language) { "deu", "ger" -> "de"; "eng" -> "en"; else -> null }
        val uri = (e.captions.firstOrNull { it.first == wanted } ?: e.captions.first()).second
        return runCatching { Vtt.parse(client.getText(uri)) }.getOrNull()
    }
    return Transcriber.cached(e.opencastId)?.first
}
